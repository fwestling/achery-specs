import { VERIFIED_HEADING, type Location, type Spec } from './types.js'

export { VERIFIED_HEADING }

const NOTE = '<!-- Generated by achery-specs from @spec test tags. Run `achery-specs write` to update; do not hand-edit. -->'

/**
 * The generated body of a spec's "Verified by" section: each live criterion and the
 * test files tagging it. A criterion with no tests but a manual marker shows its
 * method instead, so a hand check never reads as a test.
 */
export const renderVerified = (spec: Spec, coverage: ReadonlyMap<string, Location[]>): string => {
  const live = spec.criteria.filter((criterion) => !criterion.deprecated)
  const lines = live.map((criterion) => {
    const files = [...new Set((coverage.get(criterion.id) ?? []).map((test) => test.file))].sort()
    if (files.length > 0) return `- **${criterion.id}** — ${files.map((file) => `\`${file}\``).join(', ')}`
    return `- **${criterion.id}** — ${criterion.manual !== null ? `manual: ${criterion.manual}` : 'untested'}`
  })
  return [NOTE, '', ...(lines.length > 0 ? lines : ['No live criteria.'])].join('\n')
}

const FENCE = /^\s*(```|~~~)/

/** Line indexes of the "Verified by" heading and of the next `## ` heading (or the end of the file). */
const findSection = (lines: string[]): { start: number; end: number } | null => {
  let fenced = false
  let start = -1
  for (const [index, line] of lines.entries()) {
    if (FENCE.test(line)) fenced = !fenced
    if (fenced || !line.startsWith('## ')) continue
    if (start !== -1) return { start, end: index }
    if (line.slice(3).trim() === VERIFIED_HEADING) start = index
  }
  return start === -1 ? null : { start, end: lines.length }
}

/** The file text with its "Verified by" section's body replaced, or null if it has no such section. */
export const replaceVerified = (text: string, rendered: string): string | null => {
  const eol = text.includes('\r\n') ? '\r\n' : '\n'
  const lines = text.split(/\r?\n/)
  const section = findSection(lines)
  if (!section) return null
  // A blank line either side; at the end of the file the trailing '' becomes the final newline
  const replacement = ['', ...rendered.split('\n'), '']
  const next = [...lines.slice(0, section.start + 1), ...replacement, ...lines.slice(section.end)]
  return next.join(eol)
}

/** Compares a section's current body with the generated one, ignoring surrounding blank lines. */
export const isVerifiedCurrent = (content: string, rendered: string): boolean => content.trim() === rendered.trim()
